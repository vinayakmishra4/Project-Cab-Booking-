DO $$
BEGIN
    IF to_regclass('ride_history') IS NULL AND to_regclass('ride') IS NOT NULL THEN
        ALTER TABLE ride RENAME TO ride_history;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS ride_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pickup_lat DOUBLE PRECISION,
    pickup_lng DOUBLE PRECISION,
    drop_lat DOUBLE PRECISION,
    drop_lng DOUBLE PRECISION,
    pickup_address VARCHAR(255),
    dropoff_address VARCHAR(255),
    distance_km DOUBLE PRECISION,
    fare DOUBLE PRECISION,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    status VARCHAR(255),
    user_id BIGINT REFERENCES users(id),
    employee_id BIGINT REFERENCES employee(id),
    cab_id BIGINT REFERENCES vehicle_details(id)
);

CREATE INDEX IF NOT EXISTS idx_ride_history_user_id ON ride_history(user_id);
CREATE INDEX IF NOT EXISTS idx_ride_history_employee_id ON ride_history(employee_id);
CREATE INDEX IF NOT EXISTS idx_ride_history_cab_id ON ride_history(cab_id);

CREATE TABLE IF NOT EXISTS billing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ride_id BIGINT NOT NULL UNIQUE REFERENCES ride_history(id),
    pickup_address VARCHAR(255) NOT NULL,
    destination_address VARCHAR(255) NOT NULL,
    fare NUMERIC(12, 2) NOT NULL,
    gst_percentage NUMERIC(5, 2) NOT NULL,
    gst_amount NUMERIC(12, 2) NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE
);
